import { describe, expect, it } from 'vitest';

import {
  compareShapes,
  shapeRefusal,
  type Catalog,
  type CatalogColumn,
  type CatalogConstraint,
  type CatalogRelation,
  type CatalogRule,
  type Difference,
} from '../../src/bot/internalSetup/utils/dataBackends/storeShape';

const SEQ = { increment: '1', min: '1', max: '9223372036854775807', cache: '1', cycle: false };

function rel(name: string, kind: CatalogRelation['kind'], extra: Partial<CatalogRelation> = {}): CatalogRelation {
  return {
    name, kind, persistence: 'p', isPartition: false, rls: false, forceRls: false,
    accessMethod: kind === 'r' ? 'heap' : null, partitionKey: null, bound: null, parent: null,
    inherits: [], indexDef: null, indexValid: null, indexTable: null, sequence: null, ...extra,
  };
}

function col(name: string, type: string, extra: Partial<CatalogColumn> = {}): CatalogColumn {
  return {
    rel: 't', name, type, notNull: true, defaultExpr: null, identity: '', generated: '', generatedExpr: null,
    collation: null, storage: 'p', notNullValidated: null, ...extra,
  };
}

function cat(parts: Partial<Catalog>): Catalog {
  return { relations: [rel('t', 'r')], columns: [], constraints: [], rules: [], ...parts };
}

const texts = (found: Catalog, reference: Catalog) => compareShapes(found, reference, 'provisioned').differences.map(d => d.text);

describe('ri4 storeShape: index validity', () => {
  it('reports no index validity line when the bot schema index is not valid either', () => {
    const ix = (valid: boolean | null) => rel('t_idx', 'i', { indexDef: 'CREATE INDEX t_idx ON smdb_data.t USING btree (a)', indexValid: valid, indexTable: 't' });
    expect(texts(cat({ relations: [rel('t', 'r'), ix(false)] }), cat({ relations: [rel('t', 'r'), ix(false)] }))).toEqual([]);
    expect(texts(cat({ relations: [rel('t', 'r'), ix(false)] }), cat({ relations: [rel('t', 'r'), ix(true)] })))
      .toEqual(['smdb_data.t_idx is not valid, so Postgres does not use it to enforce or search']);
  });
});

describe('ri4 storeShape: sequence lines', () => {
  it('lists a sequence increment before its minimum', () => {
    const found = cat({ relations: [rel('s', 'S', { sequence: { ...SEQ, increment: '2', min: '5' } })] });
    const reference = cat({ relations: [rel('s', 'S', { sequence: { ...SEQ } })] });
    expect(texts(found, reference)).toEqual([
      "sequence smdb_data.s has increment 2, where this bot's schema has 1",
      "sequence smdb_data.s has minimum 5, where this bot's schema has 1",
    ]);
  });
});

describe('ri4 storeShape: NOT NULL validity', () => {
  const line = "smdb_data.t column a has NOT NULL NOT VALID, where this bot's schema has it validated";
  const run = (f: boolean | null, r: boolean | null) =>
    texts(cat({ columns: [col('a', 'integer', { notNullValidated: f })] }), cat({ columns: [col('a', 'integer', { notNullValidated: r })] }));

  it('reports nothing when both NOT NULL constraints are validated', () => {
    expect(run(true, true)).toEqual([]);
    expect(run(null, true)).toEqual([]);
  });

  it('reports nothing when the bot schema constraint is not validated either', () => {
    expect(run(false, false)).toEqual([]);
    expect(run(false, null)).toEqual([]);
  });

  it('reports a NOT VALID constraint where the bot schema has it validated', () => {
    expect(run(false, true)).toEqual([line]);
  });
});

describe('ri4 storeShape: column nature', () => {
  const run = (f: Partial<CatalogColumn>, r: Partial<CatalogColumn>) =>
    texts(cat({ columns: [col('g', 'integer', f)] }), cat({ columns: [col('g', 'integer', r)] }));

  it('reports a generated column whose kind of generation differs', () => {
    expect(run({ generated: 'v', generatedExpr: '(a + 1)' }, { generated: 's', generatedExpr: '(a + 1)' })).toEqual([
      "smdb_data.t column g is a generated column ((a + 1)) (GENERATED BY DEFAULT), where this bot's schema has a generated column ((a + 1)) (GENERATED BY DEFAULT)",
    ]);
  });

  it('reports a generated column whose expression differs', () => {
    expect(run({ generated: 's', generatedExpr: '(a + 1)' }, { generated: 's', generatedExpr: '(a + 2)' })).toEqual([
      "smdb_data.t column g is a generated column ((a + 1)), where this bot's schema has a generated column ((a + 2))",
    ]);
  });

  it('names GENERATED ALWAYS on the store and GENERATED BY DEFAULT in the bot schema', () => {
    expect(run({ identity: 'a' }, { identity: 'd' })).toEqual([
      "smdb_data.t column g is an identity column (GENERATED ALWAYS), where this bot's schema has an identity column (GENERATED BY DEFAULT)",
    ]);
  });

  it('names GENERATED BY DEFAULT on the store and GENERATED ALWAYS in the bot schema', () => {
    expect(run({ identity: 'd' }, { identity: 'a' })).toEqual([
      "smdb_data.t column g is an identity column (GENERATED BY DEFAULT), where this bot's schema has an identity column (GENERATED ALWAYS)",
    ]);
  });
});

describe('ri4 storeShape: collation', () => {
  const run = (f: string | null, r: string | null) =>
    texts(cat({ columns: [col('c', 'text', { collation: f })] }), cat({ columns: [col('c', 'text', { collation: r })] }));

  it('says none for a store column without a collation', () => {
    expect(run(null, '"C"')).toEqual(["smdb_data.t column c uses collation none, where this bot's schema uses \"C\""]);
  });

  it('says none for a bot schema column without a collation', () => {
    expect(run('"C"', null)).toEqual(["smdb_data.t column c uses collation \"C\", where this bot's schema uses none"]);
  });
});

describe('ri4 storeShape: constraints', () => {
  const con = (extra: Partial<CatalogConstraint>): CatalogConstraint => ({
    rel: 't', name: 't_chk', type: 'c', def: 'CHECK ((a > 0))', validated: true, ...extra,
  });

  it('adds NOT VALID to an unvalidated constraint whose text holds those words before its end', () => {
    const def = "CHECK ((c <> ' NOT VALID here'::text))";
    expect(texts(cat({ constraints: [con({ def, validated: false })] }), cat({}))).toEqual([
      `smdb_data.t has constraint t_chk (${def} NOT VALID), which this bot's schema does not have`,
    ]);
  });

  it('reports a constraint whose type differs with the same definition', () => {
    expect(texts(cat({ constraints: [con({ type: 'u', def: 'UNIQUE (a)' })] }), cat({ constraints: [con({ type: 'p', def: 'UNIQUE (a)' })] }))).toEqual([
      "smdb_data.t constraint t_chk is UNIQUE (a), where this bot's schema has UNIQUE (a)",
    ]);
  });
});

describe('ri4 storeShape: triggers, rules and policies', () => {
  const rule = (name: string, def: string): CatalogRule => ({ rel: 't', what: 'trigger', name, def });
  const a = rule('ta', 'CREATE TRIGGER ta BEFORE INSERT ON smdb_data.t FOR EACH ROW EXECUTE FUNCTION fa()');
  const b = rule('tb', 'CREATE TRIGGER tb BEFORE INSERT ON smdb_data.t FOR EACH ROW EXECUTE FUNCTION fb()');

  it('reports nothing when the store holds the same triggers', () => {
    expect(texts(cat({ rules: [a, b] }), cat({ rules: [a, b] }))).toEqual([]);
  });

  it('reports a trigger the store lacks while it holds another', () => {
    expect(texts(cat({ rules: [b] }), cat({ rules: [a, b] }))).toEqual([`smdb_data.t lacks trigger ta (${a.def})`]);
  });
});

describe('ri4 storeShape: unversioned counting', () => {
  it('counts a partition whose parent is outside smdb_data instead of listing it', () => {
    const reference = cat({ relations: [
      rel('pt', 'p', { accessMethod: null, partitionKey: 'HASH (a)' }),
      rel('pt_p0', 'r', { isPartition: true, parent: 'other_sch.pt', bound: 'FOR VALUES WITH (modulus 2, remainder 0)' }),
    ] });
    const found = cat({ relations: [rel('pt', 'p', { accessMethod: null, partitionKey: 'HASH (a)' })] });
    const result = compareShapes(found, reference, 'unversioned');
    expect(result.differences.map(d => d.text)).toEqual([]);
    expect(result.counted).toBe(1);
  });

  it('counts a table that is not a partition even when it names a held parent', () => {
    const reference = cat({ relations: [rel('pt', 'r'), rel('child', 'r', { parent: 'smdb_data.pt' })] });
    const found = cat({ relations: [rel('pt', 'r')] });
    const result = compareShapes(found, reference, 'unversioned');
    expect(result.differences.map(d => d.text)).toEqual([]);
    expect(result.counted).toBe(1);
  });
});

describe('ri4 storeShape: missing partitioned table', () => {
  it('tells the operator to restore a backup when a partitioned table is missing', () => {
    const reference = cat({ relations: [rel('t', 'r'), rel('pt', 'p', { accessMethod: null, partitionKey: 'HASH (a)' })] });
    const result = compareShapes(cat({}), reference, 'provisioned');
    expect(result.differences.map(d => d.text)).toEqual(['smdb_data.pt (partitioned table) is missing']);
    expect(shapeRefusal(result.differences).fix).toContain("a table or partition reported missing may have held data that is not in this database: restore a backup (the manager's Database window) rather than creating it empty");
  });
});

describe('ri4 storeShape: refusal reason length', () => {
  it('lists exactly five differences without a count of more', () => {
    const diffs: Difference[] = [1, 2, 3, 4, 5].map(i => ({ text: `d${i}`, key: [1, 't', 0, String(i)] }));
    const reason = shapeRefusal(diffs).reason;
    expect(reason.endsWith(': d1; d2; d3; d4; d5')).toBe(true);
    expect(reason).not.toContain('more');
  });
});
